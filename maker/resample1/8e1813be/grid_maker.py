def sample_colors(num_examples=None) -> dict:
    bgc, sqc = random.sample(range(10), 2)
    n_ex = num_examples if num_examples else 3
    variants = [{"mirror": False}, {"mirror": True}]
    if n_ex >= 2:
        ex = [dict(v) for v in variants]
        ex += [{"mirror": random.choice((True, False))} for _ in range(n_ex - 2)]
        random.shuffle(ex)
    else:
        ex = [dict(random.choice(variants))]
    plan = ex + [dict(random.choice(ex))]
    return {"bgc": bgc, "sqc": sqc, "instance_plan": plan}


def generate(diff_lb, diff_ub, max_h, max_w, bgc, sqc, mirror=None, **kw) -> dict:
    def unifint(lb, ub, rng):
        a, b = rng
        if b < a:
            b = a
        d = random.uniform(lb, ub)
        return max(a, min(b, round(a + (b - a) * d)))

    if mirror is None:
        mirror = random.choice((True, False))
    lim_rows = max_w if mirror else max_h
    lim_cols = max_h if mirror else max_w
    remcols = [c for c in range(10) if c not in (bgc, sqc)]
    nbars = unifint(diff_lb, diff_ub, (3, min(8, lim_rows // 3, lim_cols - 3)))
    ccols = random.sample(remcols, nbars)
    w = unifint(diff_lb, diff_ub, (nbars + 3, lim_cols))
    hmarg = unifint(diff_lb, diff_ub, (2 * nbars, lim_rows - nbars))
    gi = [[c] * w for c in ccols]
    go = [[c] * nbars for c in ccols]
    for _ in range(hmarg):
        idx = random.randint(0, len(go) - 1)
        gi = gi[:idx] + [[bgc] * w] + gi[idx:]
    h2 = nbars + hmarg
    n = nbars
    loci = random.randint(1, h2 - n - 2)
    locj = random.randint(1, w - n - 2)
    for i in range(loci - 1, loci + n + 1):
        for j in range(locj - 1, locj + n + 1):
            inside = loci <= i < loci + n and locj <= j < locj + n
            gi[i][j] = sqc if inside else bgc
    gi = np.array(gi)
    go = np.array(go)
    if mirror:
        gi = gi.T
        go = go.T
    return {"input": gi.tolist(), "output": go.tolist()}


def derive_operations(I, O, examples=None):
    I = np.asarray(I, dtype=int)
    hi, wi = I.shape
    # background: always the majority (>= 2*nbars blank lines vs nbars bar lines)
    bgc = Counter(I.flatten().tolist()).most_common(1)[0][0]
    cellmap = {}
    for col in set(I.flatten().tolist()) - {bgc}:
        rs, cs = np.nonzero(I == col)
        cellmap[col] = (rs.tolist(), cs.tolist())
    # Square = the colour block spanning several rows AND columns; it fixes the output size.
    sqc = max(cellmap, key=lambda k: min(len(set(cellmap[k][0])), len(set(cellmap[k][1]))))
    rs, cs = cellmap.pop(sqc)
    r0, c0, n = min(rs), min(cs), max(rs) - min(rs) + 1
    # Bar orientation: a bar is a single row (horizontal) or a single column (vertical).
    if any(len(set(v[1])) > 1 for v in cellmap.values()):
        horiz = True
    elif any(len(set(v[0])) > 1 for v in cellmap.values()):
        horiz = False
    else:  # every bar reduced to one cell beside the square: horizontal ones sit in its row band
        horiz = all(r0 - 1 <= v[0][0] <= r0 + n for v in cellmap.values())
    bars = sorted(((v[0][0] if horiz else v[1][0]), col) for col, v in cellmap.items())

    ops, sels = [], []
    # Crop canvas to the square (full n x n rectangle intended): it fixes the output size.
    ops.append(33); sels.append([r0, c0, n - 1, n - 1])
    # Paint each row (horizontal bars) / column (vertical bars) with the bar colours in order.
    for k, (_, col) in enumerate(bars):
        cells = [(k, j) for j in range(n)] if horiz else [(i, k) for i in range(n)]
        ops.append(int(col)); sels.append(sel_of(cells))
    ops.append(34); sels.append([0, 0, n - 1, n - 1])
    return ops, sels


# ── GridMaker ─────────────────────────────────────────────────────────────────

class GridMaker(BaseGridMaker):

    def parse(self, **kwargs) -> List[Tuple[
        List[NDArray], List[NDArray],
        List[NDArray], List[NDArray],
        Dict[str, Any],
    ]]:
        num_samples  = kwargs.get("num_samples", 1)
        num_examples = kwargs.get("num_examples", 3)
        max_h, max_w = kwargs.get("max_grid_dim", [30, 30])
        dataset = []

        for _sn in range(num_samples):
            # Episode-level retry: if 10 attempts at some instance all fail, that's
            # transient (bad luck with the generator's randomness) — retry the WHOLE
            # episode from scratch (fresh colors/instance plan) up to 5 times, rather
            # than silently continuing with a partial episode (fewer examples than
            # requested, or a missing test instance with operations=[]/selections=[]
            # quietly appended as if it were a normal sample).
            for _episode_attempt in range(5):
                pr_in:  List[NDArray] = []
                pr_out: List[NDArray] = []
                ex_in:  List[NDArray] = []
                ex_out: List[NDArray] = []
                ops:  List[int]       = []
                sels: List[List[int]] = []

                # sample color roles once per episode → consistent across all instances
                # sample_colors() may optionally accept num_examples (to pre-plan
                # per-instance categories) — call it either way for compatibility
                # with grid_makers generated before this parameter existed.
                if "num_examples" in inspect.signature(sample_colors).parameters:
                    colors = sample_colors(num_examples=num_examples)
                else:
                    colors = sample_colors()

                # Plans are consumed by INDEX, not mutated: retries for instance j
                # must receive the same variant. category_plan is retained as a
                # backwards-compatible single-key form; new makers use kwargs dict entries.
                category_plan = colors.pop("category_plan", None) if isinstance(colors, dict) else None
                instance_plan = colors.pop("instance_plan", None) if isinstance(colors, dict) else None
                if category_plan is not None and instance_plan is not None:
                    raise ValueError(
                        "sample_colors must return only one of category_plan/instance_plan"
                    )
                if category_plan is not None and len(category_plan) != num_examples + 1:
                    # A wrong plan length is a deterministic bug in sample_colors(),
                    # not bad luck — retrying the episode won't fix it. Fail loudly
                    # instead of clamping the index and silently reusing an entry.
                    raise ValueError(
                        f"category_plan length {len(category_plan)} != "
                        f"num_examples+1 ({num_examples + 1}) for task 8e1813be"
                    )
                if instance_plan is not None:
                    if len(instance_plan) != num_examples + 1:
                        raise ValueError(
                            f"instance_plan length {len(instance_plan)} != "
                            f"num_examples+1 ({num_examples + 1}) for task 8e1813be"
                        )
                    if any(not isinstance(entry, dict) for entry in instance_plan):
                        raise ValueError("every instance_plan entry must be a kwargs dict")
                    if instance_plan[-1] not in instance_plan[:-1]:
                        raise ValueError(
                            "instance_plan test variant must appear among the examples"
                        )

                try:
                    j = 0
                    while j < num_examples + 1:
                        ok = False
                        for _ in range(10):
                            try:
                                call_kwargs = dict(colors)
                                if instance_plan is not None:
                                    call_kwargs.update(instance_plan[j])
                                elif category_plan is not None:
                                    call_kwargs["category"] = category_plan[j]
                                r = generate(
                                    random.uniform(0.2, 0.5),
                                    random.uniform(0.5, 0.8),
                                    max_h, max_w,
                                    **call_kwargs,
                                )
                                I = np.array(r["input"],  dtype=np.uint8)
                                O = np.array(r["output"], dtype=np.uint8)
                                # enforce max_grid_dim — skip oversized grids
                                if I.shape[0] > max_h or I.shape[1] > max_w:
                                    continue
                                if O.shape[0] > max_h or O.shape[1] > max_w:
                                    continue
                                ok = True
                                break
                            except (IndexError, ValueError, KeyError):
                                continue
                        if not ok:
                            raise RuntimeError(
                                f"Failed to generate instance {j} after 10 attempts "
                                f"for task 8e1813be"
                            )
                        if j == num_examples:
                            pr_in.append(I)
                            pr_out.append(O)
                            ops, sels = derive_operations(I, O)
                        else:
                            ex_in.append(I)
                            ex_out.append(O)
                        j += 1
                    break  # episode complete
                except RuntimeError:
                    continue
            else:
                raise RuntimeError(
                    f"Failed to build a complete episode for task 8e1813be "
                    f"after 5 attempts"
                )

            dataset.append((ex_in, ex_out, pr_in, pr_out, {
                "id":         f"8e1813be-rearc-llm_{_sn + 1}",
                "concept":    "RE-ARC LLM",
                "operations": ops,
                "selections": sels,
            }))

        return dataset
