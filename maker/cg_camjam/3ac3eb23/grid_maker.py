ROTS = [0, 1, 2, 3]


def sample_colors(num_examples=None) -> dict:
    bgc = random.choice(range(10))
    n_ex = num_examples if num_examples else 3
    if n_ex >= len(ROTS):
        ex = [{"rot": r} for r in ROTS]
        ex += [{"rot": random.choice(ROTS)} for _ in range(n_ex - len(ROTS))]
        random.shuffle(ex)
    else:
        ex = [{"rot": r} for r in random.sample(ROTS, n_ex)]
    plan = ex + [dict(random.choice(ex))]
    return {"bgc": bgc, "instance_plan": plan}


def generate(diff_lb, diff_ub, max_h, max_w, bgc, rot=None) -> dict:
    def unifint(lb, ub, rng):
        a, b = rng
        if b < a:
            b = a
        d = random.uniform(lb, ub)
        return max(a, min(b, int(round(a + d * (b - a)))))

    if rot is None:
        rot = random.choice(ROTS)
    if rot % 2 == 0:
        H, W = max_h, max_w
    else:
        H, W = max_w, max_h
    h = unifint(diff_lb, diff_ub, (3, min(30, H)))
    w = unifint(diff_lb, diff_ub, (3, min(30, W)))
    remcols = [c for c in range(10) if c != bgc]
    nlocs = unifint(diff_lb, diff_ub, (1, max(1, (w - 2) // 3)))
    locopts = list(range(1, w - 1))
    gi = np.full((h, w), bgc, dtype=int)
    go = np.full((h, w), bgc, dtype=int)
    for _ in range(nlocs):
        if not locopts:
            break
        locj = random.choice(locopts)
        locopts = [x for x in locopts if not (locj - 2 <= x <= locj + 2)]
        col = random.choice(remcols)
        gi[0, locj] = col
        for p in range(0, h, 2):
            go[p, locj] = col
        for p in range(1, h, 2):
            go[p, locj - 1] = col
            go[p, locj + 1] = col
    gi = np.rot90(gi, -rot)
    go = np.rot90(go, -rot)
    return {"input": gi.tolist(), "output": go.tolist()}


def derive_operations(I, O, examples=None):
    """
    Reading (whole-band): the seed border line plus the line next to it form ONE
    2-deep band spanning the whole border; the inner line is every seed spread one
    step sideways. The output is that band tiled with period 2 across the grid.
    So: (1) paint the wings of every seed -> the band is complete, (2) copy the
    whole band rectangle once, (3) paste it at every even depth, (4) fill the lone
    far line if the depth is odd. Colour-0 seeds are invisible to Copy/Paste and
    get their fans painted directly. O is never consulted.
    """
    I = np.asarray(I, dtype=int)
    hi, wi = I.shape
    bgc = Counter(I.flatten().tolist()).most_common(1)[0][0]
    seeds = [(r, c) for r in range(hi) for c in range(wi) if I[r, c] != bgc]

    if all(r == 0 for r, _ in seeds):
        u, v, D, L = (1, 0), (0, 1), hi, wi
    elif all(r == hi - 1 for r, _ in seeds):
        u, v, D, L = (-1, 0), (0, 1), hi, wi
    elif all(c == 0 for _, c in seeds):
        u, v, D, L = (0, 1), (1, 0), wi, hi
    else:
        u, v, D, L = (0, -1), (1, 0), wi, hi

    def cell(s, d, t):
        return (s[0] + u[0] * d + v[0] * t, s[1] + u[1] * d + v[1] * t)

    def line_cells(d):
        # every cell of the grid line at depth d from the seed border
        if v == (0, 1):
            r = cell(seeds[0], d, 0)[0]
            return [(r, c) for c in range(wi)]
        c = cell(seeds[0], d, 0)[1]
        return [(r, c) for r in range(hi)]

    def rect_of(cells):
        r0 = min(p[0] for p in cells); r1 = max(p[0] for p in cells)
        c0 = min(p[1] for p in cells); c1 = max(p[1] for p in cells)
        return r0, c0, r1, c1

    ops, sels = [], []

    # (1) spread every seed one step sideways -> the 2-deep band is complete
    for s in seeds:
        col = int(I[s[0], s[1]])
        ops.append(col)
        sels.append(sel_of([cell(s, 1, -1), cell(s, 1, 1)]))

    P = D // 2
    nonzero = [s for s in seeds if I[s[0], s[1]] != 0]
    if nonzero and P > 1:
        # (2) copy the whole band (full rectangle: depth 0..1, whole border length)
        r0, c0, r1, c1 = rect_of(line_cells(0) + line_cells(1))
        ops.append(29)
        sels.append([r0, c0, r1 - r0, c1 - c0])
        # (3) stamp it at every even depth
        for k in range(1, P):
            pr0, pc0, _, _ = rect_of(line_cells(2 * k) + line_cells(2 * k + 1))
            ops.append(30)
            sels.append([pr0, pc0, 0, 0])
        # (4) odd depth: the lone far line carries only the seed lanes
        if D % 2 == 1:
            bycol = {}
            for s in nonzero:
                bycol.setdefault(int(I[s[0], s[1]]), []).append(cell(s, D - 1, 0))
            for col, cells in bycol.items():
                ops.append(col)
                sels.append(sel_of(cells))
        rest = [s for s in seeds if I[s[0], s[1]] == 0]
    else:
        rest = list(seeds)

    # seeds not carried by the band copy: paint their whole remaining fan
    for s in rest:
        col = int(I[s[0], s[1]])
        fan = []
        for d in range(2, D):
            for t in ((0,) if d % 2 == 0 else (-1, 1)):
                fan.append(cell(s, d, t))
        if fan:
            ops.append(col)
            sels.append(sel_of(fan))

    ops.append(34)
    sels.append([0, 0, hi - 1, wi - 1])
    return ops, sels


# ── GridMaker ─────────────────────────────────────────────────────────────────

class GridMaker(BaseGridMaker):

    def parse(self, **kwargs) -> List[Tuple[
        List[NDArray], List[NDArray],
        List[NDArray], List[NDArray],
        Dict[str, Any],
    ]]:
        num_samples  = kwargs.get("num_samples", 1)
        num_examples = kwargs.get("num_examples", 3)
        max_h, max_w = kwargs.get("max_grid_dim", [30, 30])
        dataset = []

        for _sn in range(num_samples):
            # Episode-level retry: if 10 attempts at some instance all fail, that's
            # transient (bad luck with the generator's randomness) — retry the WHOLE
            # episode from scratch (fresh colors/instance plan) up to 5 times, rather
            # than silently continuing with a partial episode (fewer examples than
            # requested, or a missing test instance with operations=[]/selections=[]
            # quietly appended as if it were a normal sample).
            for _episode_attempt in range(5):
                pr_in:  List[NDArray] = []
                pr_out: List[NDArray] = []
                ex_in:  List[NDArray] = []
                ex_out: List[NDArray] = []
                ops:  List[int]       = []
                sels: List[List[int]] = []

                # sample color roles once per episode → consistent across all instances
                # sample_colors() may optionally accept num_examples (to pre-plan
                # per-instance categories) — call it either way for compatibility
                # with grid_makers generated before this parameter existed.
                if "num_examples" in inspect.signature(sample_colors).parameters:
                    colors = sample_colors(num_examples=num_examples)
                else:
                    colors = sample_colors()

                # Plans are consumed by INDEX, not mutated: retries for instance j
                # must receive the same variant. category_plan is retained as a
                # backwards-compatible single-key form; new makers use kwargs dict entries.
                category_plan = colors.pop("category_plan", None) if isinstance(colors, dict) else None
                instance_plan = colors.pop("instance_plan", None) if isinstance(colors, dict) else None
                if category_plan is not None and instance_plan is not None:
                    raise ValueError(
                        "sample_colors must return only one of category_plan/instance_plan"
                    )
                if category_plan is not None and len(category_plan) != num_examples + 1:
                    # A wrong plan length is a deterministic bug in sample_colors(),
                    # not bad luck — retrying the episode won't fix it. Fail loudly
                    # instead of clamping the index and silently reusing an entry.
                    raise ValueError(
                        f"category_plan length {len(category_plan)} != "
                        f"num_examples+1 ({num_examples + 1}) for task 3ac3eb23"
                    )
                if instance_plan is not None:
                    if len(instance_plan) != num_examples + 1:
                        raise ValueError(
                            f"instance_plan length {len(instance_plan)} != "
                            f"num_examples+1 ({num_examples + 1}) for task 3ac3eb23"
                        )
                    if any(not isinstance(entry, dict) for entry in instance_plan):
                        raise ValueError("every instance_plan entry must be a kwargs dict")
                    if instance_plan[-1] not in instance_plan[:-1]:
                        raise ValueError(
                            "instance_plan test variant must appear among the examples"
                        )

                try:
                    j = 0
                    while j < num_examples + 1:
                        ok = False
                        for _ in range(10):
                            try:
                                call_kwargs = dict(colors)
                                if instance_plan is not None:
                                    call_kwargs.update(instance_plan[j])
                                elif category_plan is not None:
                                    call_kwargs["category"] = category_plan[j]
                                r = generate(
                                    random.uniform(0.2, 0.5),
                                    random.uniform(0.5, 0.8),
                                    max_h, max_w,
                                    **call_kwargs,
                                )
                                I = np.array(r["input"],  dtype=np.uint8)
                                O = np.array(r["output"], dtype=np.uint8)
                                # enforce max_grid_dim — skip oversized grids
                                if I.shape[0] > max_h or I.shape[1] > max_w:
                                    continue
                                if O.shape[0] > max_h or O.shape[1] > max_w:
                                    continue
                                ok = True
                                break
                            except (IndexError, ValueError, KeyError):
                                continue
                        if not ok:
                            raise RuntimeError(
                                f"Failed to generate instance {j} after 10 attempts "
                                f"for task 3ac3eb23"
                            )
                        if j == num_examples:
                            pr_in.append(I)
                            pr_out.append(O)
                            ops, sels = derive_operations(I, O)
                        else:
                            ex_in.append(I)
                            ex_out.append(O)
                        j += 1
                    break  # episode complete
                except RuntimeError:
                    continue
            else:
                raise RuntimeError(
                    f"Failed to build a complete episode for task 3ac3eb23 "
                    f"after 5 attempts"
                )

            dataset.append((ex_in, ex_out, pr_in, pr_out, {
                "id":         f"3ac3eb23-rearc-llm_{_sn + 1}",
                "concept":    "RE-ARC LLM",
                "operations": ops,
                "selections": sels,
            }))

        return dataset
