def sample_colors(num_examples=None) -> dict:
    # The rule never depends on which colours are used; the only structural
    # variant is band orientation (vertical stack -> column answer, or
    # horizontal sequence -> row answer). Cover both in the examples.
    n_ex = num_examples if num_examples else 3
    variants = [{"flip": False}, {"flip": True}]
    if n_ex >= 2:
        ex = [dict(v) for v in variants] + [dict(random.choice(variants)) for _ in range(n_ex - 2)]
        random.shuffle(ex)
    else:
        ex = [dict(random.choice(variants))]
    return {"instance_plan": ex + [dict(random.choice(ex))]}


def generate(diff_lb, diff_ub, max_h, max_w, flip=None, **kw) -> dict:
    def unifint(lb, ub, rng):
        a, b = rng
        if b <= a:
            return a
        d = random.uniform(lb, ub)
        return max(a, min(b, int(round(a + d * (b - a)))))

    if flip is None:
        flip = random.choice((True, False))
    # before the optional final dmirror the grid is h x w; after it, w x h
    H, W = (max_w, max_h) if flip else (max_h, max_w)
    h = unifint(diff_lb, diff_ub, (4, max(4, min(30, H))))
    w = unifint(diff_lb, diff_ub, (6, max(6, min(30, W))))
    numcolors = unifint(diff_lb, diff_ub, (2, w // 3))
    ccols = random.sample(range(10), numcolors)
    cols = []
    for c in ccols:
        cols += [c] * 3
    while len(cols) < w:
        idx = random.randint(0, len(cols) - 1)
        cols = cols[:idx] + cols[idx:idx + 1] + cols[idx:]
    gi = [list(cols) for _ in range(h)]
    nd = unifint(diff_lb, diff_ub, (0, 3 * h * numcolors))
    for _ in range(nd):
        options = []
        for a in range(h):
            for b in range(w - 3):
                if gi[a][b] == gi[a][b + 1] and gi[a][b + 2] == gi[a][b + 3]:
                    options.append((a, b, gi[a][b], gi[a][b + 2]))
        if not options:
            break
        a, b, c1, c2 = random.choice(options)
        if random.choice((True, False)):
            gi[a][b + 1] = c2
        else:
            gi[a][b + 2] = c1
    go = [list(ccols)]
    if flip:
        gi = [list(r) for r in zip(*gi)]
        go = [list(r) for r in zip(*go)]
    return {"input": gi, "output": go}


def derive_operations(I, O=None, examples=None):
    I = np.asarray(I, dtype=int)
    hi, wi = I.shape
    ops, sels = [], []

    # Bands are stacked top->bottom when row 0 is one flat colour,
    # otherwise they run left->right.
    vertical = len(set(I[0, :].tolist())) == 1
    line = I[:, 0].tolist() if vertical else I[0, :].tolist()

    # Each band is represented by its first cell along the leading line
    # (column 0 for stacked bands, row 0 for side-by-side bands).
    reps = []
    seen = set()
    for p, v in enumerate(line):
        if v not in seen:
            seen.add(v)
            reps.append((p, v))
    k = len(reps)

    pos = (lambda t: (t, 0)) if vertical else (lambda t: (0, t))
    step_op = 20 if vertical else 23          # MoveU / MoveL toward the front
    cur = list(line)

    # Slide each band's representative cell forward into its rank slot j,
    # bands handled in order of appearance.
    for j, (p, col) in enumerate(reps):
        if p == j:
            continue                           # already sits at its rank slot
        if col == 0:
            # a 0-coloured cell cannot be grabbed by Move; paint the slot instead
            if cur[j] != 0:
                ops.append(0); sels.append(sel_of([pos(j)]))
                cur[j] = 0
            continue
        ops.append(step_op); sels.append(sel_of([pos(p)]))     # grab the cell
        for _ in range(p - j - 1):
            ops.append(step_op); sels.append(sel_of([]))       # keep sliding it
        cur[j] = col
        cur[p] = 0

    # Keep only the strip of k rank slots (full rectangle 1xk / kx1).
    strip = [0, 0, k - 1, 0] if vertical else [0, 0, 0, k - 1]
    ops.append(33); sels.append(strip)
    ops.append(34); sels.append(strip)
    return ops, sels


# ── GridMaker ─────────────────────────────────────────────────────────────────

class GridMaker(BaseGridMaker):

    def parse(self, **kwargs) -> List[Tuple[
        List[NDArray], List[NDArray],
        List[NDArray], List[NDArray],
        Dict[str, Any],
    ]]:
        num_samples  = kwargs.get("num_samples", 1)
        num_examples = kwargs.get("num_examples", 3)
        max_h, max_w = kwargs.get("max_grid_dim", [30, 30])
        dataset = []

        for _sn in range(num_samples):
            # Episode-level retry: if 10 attempts at some instance all fail, that's
            # transient (bad luck with the generator's randomness) — retry the WHOLE
            # episode from scratch (fresh colors/instance plan) up to 5 times, rather
            # than silently continuing with a partial episode (fewer examples than
            # requested, or a missing test instance with operations=[]/selections=[]
            # quietly appended as if it were a normal sample).
            for _episode_attempt in range(5):
                pr_in:  List[NDArray] = []
                pr_out: List[NDArray] = []
                ex_in:  List[NDArray] = []
                ex_out: List[NDArray] = []
                ops:  List[int]       = []
                sels: List[List[int]] = []

                # sample color roles once per episode → consistent across all instances
                # sample_colors() may optionally accept num_examples (to pre-plan
                # per-instance categories) — call it either way for compatibility
                # with grid_makers generated before this parameter existed.
                if "num_examples" in inspect.signature(sample_colors).parameters:
                    colors = sample_colors(num_examples=num_examples)
                else:
                    colors = sample_colors()

                # Plans are consumed by INDEX, not mutated: retries for instance j
                # must receive the same variant. category_plan is retained as a
                # backwards-compatible single-key form; new makers use kwargs dict entries.
                category_plan = colors.pop("category_plan", None) if isinstance(colors, dict) else None
                instance_plan = colors.pop("instance_plan", None) if isinstance(colors, dict) else None
                if category_plan is not None and instance_plan is not None:
                    raise ValueError(
                        "sample_colors must return only one of category_plan/instance_plan"
                    )
                if category_plan is not None and len(category_plan) != num_examples + 1:
                    # A wrong plan length is a deterministic bug in sample_colors(),
                    # not bad luck — retrying the episode won't fix it. Fail loudly
                    # instead of clamping the index and silently reusing an entry.
                    raise ValueError(
                        f"category_plan length {len(category_plan)} != "
                        f"num_examples+1 ({num_examples + 1}) for task 4be741c5"
                    )
                if instance_plan is not None:
                    if len(instance_plan) != num_examples + 1:
                        raise ValueError(
                            f"instance_plan length {len(instance_plan)} != "
                            f"num_examples+1 ({num_examples + 1}) for task 4be741c5"
                        )
                    if any(not isinstance(entry, dict) for entry in instance_plan):
                        raise ValueError("every instance_plan entry must be a kwargs dict")
                    if instance_plan[-1] not in instance_plan[:-1]:
                        raise ValueError(
                            "instance_plan test variant must appear among the examples"
                        )

                try:
                    j = 0
                    while j < num_examples + 1:
                        ok = False
                        for _ in range(10):
                            try:
                                call_kwargs = dict(colors)
                                if instance_plan is not None:
                                    call_kwargs.update(instance_plan[j])
                                elif category_plan is not None:
                                    call_kwargs["category"] = category_plan[j]
                                r = generate(
                                    random.uniform(0.2, 0.5),
                                    random.uniform(0.5, 0.8),
                                    max_h, max_w,
                                    **call_kwargs,
                                )
                                I = np.array(r["input"],  dtype=np.uint8)
                                O = np.array(r["output"], dtype=np.uint8)
                                # enforce max_grid_dim — skip oversized grids
                                if I.shape[0] > max_h or I.shape[1] > max_w:
                                    continue
                                if O.shape[0] > max_h or O.shape[1] > max_w:
                                    continue
                                ok = True
                                break
                            except (IndexError, ValueError, KeyError):
                                continue
                        if not ok:
                            raise RuntimeError(
                                f"Failed to generate instance {j} after 10 attempts "
                                f"for task 4be741c5"
                            )
                        if j == num_examples:
                            pr_in.append(I)
                            pr_out.append(O)
                            ops, sels = derive_operations(I, O)
                        else:
                            ex_in.append(I)
                            ex_out.append(O)
                        j += 1
                    break  # episode complete
                except RuntimeError:
                    continue
            else:
                raise RuntimeError(
                    f"Failed to build a complete episode for task 4be741c5 "
                    f"after 5 attempts"
                )

            dataset.append((ex_in, ex_out, pr_in, pr_out, {
                "id":         f"4be741c5-rearc-llm_{_sn + 1}",
                "concept":    "RE-ARC LLM",
                "operations": ops,
                "selections": sels,
            }))

        return dataset
